/**
 * Owner, 2026-10-08: legal text is formal wherever the locale distinguishes.
 * Appended to every `legal` row outside the withdrawal instruction (official wording)
 * so no row's own context has to repeat it.
 */
const LEGAL_REGISTER_NOTE =
  ' Register note: legal text (`legal.ts`) is FORMAL in every locale that distinguishes -- fr vous, es usted (third-person verbs), it Lei/Suo (capitalised, as the withdrawal text writes it), nl u/uw, pl Państwo, ru вы, uk ви, bg вие/ви (lowercase), tr siz, pt-PT third-person formal ("pode ... a sua", "o utilizador"), zh 您, ja polite. de and sv keep informal du. Derive the formal wording from this locale\'s withdrawal text. One AI term per locale: tr Yapay Zeka, bg ИИ, it IA; "Vertex AI" stays a product name. See .claude/rules/i18n.md.';
const LEGAL_REGISTER_EXEMPT = /^withdrawal\./;

// `module` is the file under src/locales/<locale>/; `file:export` addresses a
// second export of it, e.g. `themes:theme_translations`.
const rows = entries.map(([moduleSpec, path, source, context, protectedTokens = []]) => {
  const [module, exportName = module] = moduleSpec.split(':');
  const acceptedReorders = ORDERED_PLACEHOLDERS[`${exportName}.${path}`];
  return {
    acceptedReorders: acceptedReorders || {},
    context:
      module === 'legal' && !LEGAL_REGISTER_EXEMPT.test(path)
        ? context + LEGAL_REGISTER_NOTE
        : context,
    exportName,
    module,
    orderedPlaceholders: Boolean(acceptedReorders),
    path,
    protectedTokens,
    source,
    verbatim: VERBATIM.has(`${exportName}.${path}`),
    // Only while the English is the one approved; a changed source reopens.
    englishIn:
      ENGLISH_IN[`${exportName}.${path}`]?.english === source
        ? ENGLISH_IN[`${exportName}.${path}`].locales
        : [],
  };
});

// Exposed so a test can prove every key of each map resolves to a row.
Object.defineProperty(rows, 'orderedPlaceholderKeys', { value: Object.keys(ORDERED_PLACEHOLDERS) });
Object.defineProperty(rows, 'verbatimKeys', { value: [...VERBATIM] });
Object.defineProperty(rows, 'englishIn', { value: ENGLISH_IN });
module.exports = rows;
