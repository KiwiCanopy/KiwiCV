import {
  COVER_LETTER_TONES,
  type CoverLetterLengthPreset,
  type CoverLetterTone,
} from '@/constants/ai';

/**
 * ⚠️ `Record<…, string>`, never a lookup with a fallback: a fifth tone or a
 * fourth preset is `TS2741` here rather than an unlabelled option at runtime.
 *
 * The tone keys themselves are pinned against the backend prompt's own table by
 * `constants/__tests__/coverLetterTones.test.ts`; that these keys NAME anything
 * is `__tests__/coverLetterControlLabels.test.ts`.
 */
export const TONE_LABEL_KEYS: Record<CoverLetterTone, string> = {
  professional: 'ai.cover_letter_tone_professional',
  warm: 'ai.cover_letter_tone_warm',
  formal: 'ai.cover_letter_tone_formal',
  confident: 'ai.cover_letter_tone_confident',
};

/**
 * The Ton select's fifth option, which is **not a tone**.
 *
 * ⚠️ **A UI-only sentinel. Never add it to `COVER_LETTER_TONES`.** That array is
 * pinned against the backend's own table, and `getCoverLetterPrompt` answers an
 * unknown tone with `UNKNOWN_LETTER_TONE` → `LETTER_BAD_REQUEST`, one of the two
 * failures a retry cannot clear. On the wire the contract is unchanged: four
 * tones XOR a writing sample. This value only tells the select which of those
 * two the user picked, and maps to the existing `matchStyle` flag.
 */
export const COVER_LETTER_STYLE_OPTION = '__style__';

/**
 * Every option the Ton select offers, tones and the sentinel alike.
 *
 * ⚠️ A `Record` over the union PLUS the sentinel, so a fifth tone is still
 * `TS2741` here — the exhaustiveness `TONE_LABEL_KEYS` buys is not given up by
 * adding the one option that is not a tone.
 */
export const TONE_OPTION_LABEL_KEYS: Record<
  CoverLetterTone | typeof COVER_LETTER_STYLE_OPTION,
  string
> = {
  ...TONE_LABEL_KEYS,
  [COVER_LETTER_STYLE_OPTION]: 'ai.cover_letter_tone_style',
};

/** The select's options in display order — the sentinel last, never among the tones. */
export const TONE_OPTION_VALUES = [...COVER_LETTER_TONES, COVER_LETTER_STYLE_OPTION] as const;

/** The label promises a page fraction, because the preset is one. */
export const LENGTH_LABEL_KEYS: Record<CoverLetterLengthPreset, string> = {
  short: 'ai.cover_letter_length_short',
  medium: 'ai.cover_letter_length_medium',
  long: 'ai.cover_letter_length_long',
};

/**
 * The missing-sample refusal line's id, derived from the control's own.
 *
 * The RUN BUTTON lives in the parent, outside `AICoverLetterControl`, and has to
 * point `aria-describedby` at this line — so the id is derived rather than
 * plumbed through props or generated by `useId`.
 */
export const coverLetterSampleReasonId = (controlId: string) => `${controlId}-needs-sample`;
